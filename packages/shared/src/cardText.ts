/**
 * Canonical form of text stored in card tables, shared by the API and the
 * offline redaction tool: NFKC, no default-ignorable (zero-width and other
 * invisible) characters, and every decimal digit written as ASCII. A digit
 * run in that form is visible to a plain `[0-9]` check, which is all the
 * database guards can express.
 */

/** Stored card text never holds this many consecutive digits; the database rejects them in every card column. */
export const LONG_DIGIT_RUN = 13;

const LONG_DIGIT_RUN_PATTERN = new RegExp(`[0-9]{${LONG_DIGIT_RUN}}`);
const DEFAULT_IGNORABLE = /\p{Default_Ignorable_Code_Point}/gu;
const NON_ASCII_DIGIT = /(?![0-9])\p{Nd}/gu;

function asciiDigit(char: string): string {
  // Unicode encodes every decimal digit set as ten contiguous code points starting at zero.
  const code = char.codePointAt(0)!;
  let zero = code;
  while (zero > 0 && /\p{Nd}/u.test(String.fromCodePoint(zero - 1))) zero -= 1;
  return String((code - zero) % 10);
}

/** Text as card tables store it: NFKC, invisible characters removed, digits in ASCII. Idempotent. */
export function normalizeCardText(text: string): string {
  return text
    .replace(DEFAULT_IGNORABLE, '')
    .normalize('NFKC')
    .replace(DEFAULT_IGNORABLE, '')
    .replace(NON_ASCII_DIGIT, asciiDigit);
}

/** True when the normalized text holds `LONG_DIGIT_RUN` or more consecutive digits, card number or not. */
export function containsLongDigitRun(text: string): boolean {
  return LONG_DIGIT_RUN_PATTERN.test(normalizeCardText(text));
}

